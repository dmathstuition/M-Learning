/* Generates supabase/seed.sql from js/seed.js so local and online modes share one source of sample content.
 * Run: node tools/gen-seed-sql.js */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const ROOT = path.resolve(__dirname, '..');
const ctx = { console, crypto: require('crypto').webcrypto, TextEncoder, btoa, atob, Date: class extends Date { static now() { return 1767225600000; } } };
ctx.window = ctx; vm.createContext(ctx);
['util', 'questions', 'seed'].forEach((f) => vm.runInContext(fs.readFileSync(path.join(ROOT, 'js', f + '.js'), 'utf8'), ctx));
const { Q, seed } = ctx.ML;
const b = seed.build({ stableIds: true });

const TAG = '$ml$';
const lit = (v) => { const j = JSON.stringify(v); if (j.includes(TAG)) throw new Error('JSON contains dollar-quote tag'); return TAG + j + TAG + '::jsonb'; };
const str = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const out = ['-- M Learning App — sample content. Generated by tools/gen-seed-sql.js; do not edit by hand.',
  '-- Run AFTER schema.sql. Safe to re-run: existing rows are left alone.', 'begin;'];
b.courses.forEach((c) => out.push(`insert into public.courses (id, data) values (${str(c.id)}, ${lit(c)}) on conflict (id) do nothing;`));
b.lessons.forEach((l) => out.push(`insert into public.lessons (id, course_id, data) values (${str(l.id)}, ${str(l.courseId)}, ${lit(l)}) on conflict (id) do nothing;`));
b.questions.forEach((q) => {
  const { data, key } = Q.splitForStorage(Object.assign({}, q, { ownerId: null }));
  out.push(`insert into public.questions (id, owner_id, owner_role, practice, bank, data) values (${str(q.id)}, null, 'teacher', ${q.practice ? 'true' : 'false'}, ${str(q.bank)}, ${lit(data)}) on conflict (id) do nothing;`);
  out.push(`insert into public.question_keys (question_id, key) values (${str(q.id)}, ${lit(key)}) on conflict (question_id) do nothing;`);
});
b.quizzes.forEach((z) => out.push(`insert into public.quizzes (id, status, created_by, data) values (${str(z.id)}, ${str(z.status)}, null, ${lit(z)}) on conflict (id) do nothing;`));
out.push('commit;', '');
fs.writeFileSync(path.join(ROOT, 'supabase', 'seed.sql'), out.join('\n'));
console.log('supabase/seed.sql:', b.courses.length, 'courses,', b.lessons.length, 'lessons,', b.questions.length, 'questions,', b.quizzes.length, 'quizzes');
